/**
 * Omni Quest's story: the chapters, the special events and the friends' daily talk (`docs/rpg-story.md`).
 * Scenes open from what the owner really did (levels, timed sessions, bounties, weekly quests), never from time
 * alone. The story is written in Thai; placeholders like `{name}` are filled by [fill].
