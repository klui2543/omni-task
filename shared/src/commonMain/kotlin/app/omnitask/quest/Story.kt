object Story {

    enum class Speaker(val label: String, val emoji: String) {
        NARRATOR("", "📖"),
        HERO("{name}", "🙂"),
        MASCOT("{mascot}", "{mascotEmoji}"),
        ORRIN("มาสเตอร์ออร์ริน", "🧙"),
        LEO("ลีโอ", "🗡️"),
        CELINE("เซลีน", "📘"),
        MIST("เสียงในหมอก", "🌫️"),
    }

    data class Line(val who: Speaker, val text: String)

    /** What opens a scene, checked against [Facts]. [hint] tells the owner what to do in real life. */
    data class Unlock(val hint: String, val open: (Facts) -> Boolean)

    data class Scene(
        val id: String,
        val chapter: Int,
        val title: String,
        val unlock: Unlock,
        val lines: List<Line>,
        val gold: Int,
        /** Set for a special event: the scene can only open while this is true. */
        val event: Boolean = false,
    )

    /** What the story knows about the owner's real progress. */
    data class Facts(
        val level: Int,
        val sessions: Int,
        val focusSeconds: Int,
        val bossSlain: Boolean,
        val weeklyDone: Boolean,
        val seen: Set<String>,
        val today: LocalDate,
        /** A shift ("เวร") in today's calendar. */
        val shiftToday: Boolean,
        /** Seven or more open tasks due within the next seven days. */
        val busyWeek: Boolean,
    )

    /** What fills the placeholders. */
    data class Cast(val name: String, val tribe: Tribe, val mascot: Tribe, val branch: String?)

