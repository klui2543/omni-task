    fun scene(id: String): Scene? = scenes.firstOrNull { it.id == id }

    /** Story scenes not seen yet whose conditions hold now. Special events wait until the first scene is seen. */
    fun open(f: Facts): List<Scene> = scenes.filter { it.id !in f.seen && (!it.event || "c1-1" in f.seen) && it.unlock.open(f) }

    /** The next chapter scene still closed, to say what opens it. */
    fun next(f: Facts): Scene? = scenes.filter { !it.event && it.id !in f.seen }.firstOrNull { !it.unlock.open(f) }

    fun fill(text: String, cast: Cast): String = text
        .replace("{name}", cast.name.ifBlank { "นักผจญภัย" })
        .replace("{mascotEmoji}", "")
        .replace("{mascot}", cast.mascot.mascot)
        .replace("{tribe}", cast.tribe.label)
        .replace("{branch}", cast.branch?.let { "#$it" } ?: "ที่เธอทำบ่อยที่สุด")

    // ---- The friends' daily talk ----

    /** What the friends see of the owner's real day. */
    data class Day(
        val today: LocalDate,
        val doneToday: Int,
        val lastDone: String?,
        val overdue: Int,
        val focusMinutes: Int,
        val topRealm: Tribe?,
        val shiftToday: Boolean,
        val nextEvent: String?,
    )

    /** One line from [who] for today; the choice stays the same all day. */
    fun talk(who: Speaker, d: Day, cast: Cast): String {
        val seed = d.today.toEpochDays().toInt() + who.ordinal * 7
        fun pick(vararg options: String?): String {
            val real = options.filterNotNull()
            return fill(real[((seed % real.size) + real.size) % real.size], cast)
        }
        return when (who) {
            Speaker.LEO -> when {
                d.shiftToday -> pick("วันนี้มีเวรใช่ไหม ข้าเฝ้ากิลด์ให้ ไปทำหน้าที่ให้เต็มที่", "เวรวันนี้ อย่าลืมกินข้าวนะ ข้าพูดจริง")
                d.focusMinutes >= 60 -> pick("จับเวลาไป ${d.focusMinutes} นาทีแล้วเหรอ! ดาบข้ายังร้อนไม่เท่านี้เลย", "วันนี้ตั้งใจจัง ข้าต้องไปซ้อมเพิ่มแล้ว")
                d.doneToday >= 3 -> pick("วันนี้ล้มไป ${d.doneToday} ตัวแล้ว! ข้าต้องเร่งแล้วสิ", d.lastDone?.let { "เห็นนะว่าเพิ่งจัดการ \"$it\" ไป เท่มาก" })
                d.overdue > 0 -> pick("มีมอนสเตอร์ค้าง ${d.overdue} ตัวนะ ไปล่าด้วยกันไหม", "ข้าท้าเลย วันนี้ใครล้มตัวค้างได้ก่อนชนะ")
                else -> pick("วันนี้ยังไม่ได้ฟันอะไรเลย ไปหาอะไรทำกันเถอะ!", "ข้าซ้อมดาบมาตั้งแต่เช้า เธอล่ะ")
            }
            Speaker.CELINE -> when {
                d.topRealm != null -> pick(
                    "ข้าจดไว้ว่าช่วงนี้แสงอรุณของเธอมาจากเรื่อง${d.topRealm.realm}มากที่สุด",
                    "สัปดาห์นี้เธอเติบโตทางเผ่า${d.topRealm.label} ข้าว่ามันบอกอะไรบางอย่าง",
                )
                d.overdue > 2 -> pick("งานค้าง ${d.overdue} อัน ลองเขียนก้าวแรกให้แต่ละอันดูไหม หมอกจับงานที่มีก้าวแรกไม่ติด")
                d.nextEvent != null -> pick("นัดถัดไปของเธอคือ \"${d.nextEvent}\" เตรียมตัวไว้ก่อนดีกว่า")
                else -> pick("วันนี้เงียบดี เหมาะกับการอ่านหนังสือ", "ข้ากำลังจดเรื่องหมอกต่อ มีอะไรเล่าให้ฟังไหม")
            }
            Speaker.ORRIN -> when {
                d.shiftToday -> pick("วันเวรไม่ต้องทำเควสให้ครบ ทำงานตรงหน้าให้ดีก็พอแล้ว")
                d.doneToday == 0 && d.overdue > 0 -> pick("เริ่มจากชิ้นเล็กที่สุดก่อน แสงอรุณดวงแรกของวันมักยากที่สุด")
                d.doneToday > 0 -> pick("ดีมาก วันนี้ได้แสงอรุณแล้ว ${d.doneToday} ดวง", "ข้าเห็นจากหน้าต่างกิลด์ กิ่งข้างนอกเขียวขึ้นอีกนิด")
                else -> pick("กระดานเควสมีของใหม่ ไปดูสิ", "พักได้ แต่อย่าหายไปเฉยๆ นะ")
            }
            else -> ""
        }
    }
